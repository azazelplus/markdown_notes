/*
3. 无重复字符的最长子串

给定一个字符串 s ，请你找出其中不含有重复字符的 最长 子串 的长度。


示例 1:

输入: s = "abcabcbb"
输出: 3 
解释: 因为无重复字符的最长子串是 "abc"，所以其长度为 3。注意 "bca" 和 "cab" 也是正确答案。
示例 2:

输入: s = "bbbbb"
输出: 1
解释: 因为无重复字符的最长子串是 "b"，所以其长度为 1。
示例 3:

输入: s = "pwwkew"
输出: 3
解释: 因为无重复字符的最长子串是 "wke"，所以其长度为 3。
请注意，你的答案必须是 子串 的长度，"pwke" 是一个子序列，不是子串。
*/

/*
思路: 这是经典的 滑动窗口 问题.核心思想是: 维护一个窗口, 用两个指针left和right, 一个表(可以是哈希也没必要)来记录当前窗口内字符出现的次数.
不断把窗口的右边界向右扩展，尝试包含新的字符。
如果新字符和窗口里已有的字符重复了，你就把窗口的左边界向右移动，直到窗口里不再有这个重复字符（也就是把这个重复字符及其左边的部分都剔除掉）。
这样，对于每个右边界位置，你得到了以这个位置为结尾的最长无重复子串（因为左边界已经尽可能靠左了，再左就会包含重复）。
记录所有这些子串的长度，取最大值，就是答案。

滑动窗口的核心要点：
0.滑动窗口通常用于找“最长/最短满足条件的子数组”或“固定窗口大小的匹配”，且窗口的和与窗口大小单调相关（需要数组元素同号）。
1.维护一个有条件的滑动窗口；
2.右端点右移，导致窗口扩大，是不满足条件的罪魁祸首；
3.左端点右移目的是为了缩小窗口，重新满足条件
*/

class Solution {
public:
    int lengthOfLongestSubstring(string s) {
        vector<int> lastPos(128,-1); //记录ASCII字符表中, 每个字符上次出现的位置，初始化为-1
        int left = 0; //滑动窗口的左边界
        int maxLength = 0; //记录最长子串的长度
        for (int right = 0; right < s.size(); right++) {
            char c = s[right];
            //如果当前字符在窗口内已经出现过，移动左边界
            if (lastPos[c] >= left) {
                left = lastPos[c] + 1; //把左边界移动到上次出现位置的右边
            }
            lastPos[c] = right; //更新字符的最新位置
            maxLength = max(maxLength, right - left + 1); //更新最长子串的长度
        }
        return maxLength;
    }
};

