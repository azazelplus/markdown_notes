/*
前缀和---解决区间求和问题

`前缀和`数组, 即prefix[i], 表示原数组前i个元素的和(即nums[0] + ... + nums[i-1]).

假设数组是 [1, 2, 3]：
    空前缀和 = 0（一个元素都没加）
    加到第1个数 1 的前缀和 = 1
    加到第2个数 2 的前缀和 = 1+2=3
    加到第3个数 3 的前缀和 = 1+2+3=6
前缀和数组就是 [0, 1, 3, 6]（长度比原数组多1，因为0代表还没加任何数）。



-----------------------------------------------------------------------------
给你一个整数数组 nums 和一个整数 k ，请你统计并返回 该数组中和为 k 的子数组的个数 。

子数组是数组中元素的连续非空序列。

 

示例 1：

输入：nums = [1,1,1], k = 2
输出：2
示例 2：

输入：nums = [1,2,3], k = 3
输出：2


经典解法: 前缀和 + 哈希表.

遍历i下, 对任意子数组nums[j..i-1], 其中j∈(0,i-1), 其和为prefix[i] - prefix[j]. 如果这个和等于k, 那么简单移项可得:
prefix[j] = prefix[i] - k
也就是说, 对于每个i, 我们需要知道有多少个j满足prefix[j] = prefix[i] - k. 而这个j一定是在i之前的(j<i), 所以在遍历i的过程中, 只要保证对每个i都将profix[i]的值加入表中, 那麽根据键值对查找, 自然地遍历了i之前所有满足条件的j的数量. 所以适合用哈希表.

用哈希表count来记录在遍历过程中, 每个前缀和数值出现了多少次(如果整个数组是正的, 越加越大, 那麽每个前缀和只会出现一次.)
*/






class Solution {
public:
    int subarraySum(vector<int>& nums, int k) {
        unordered_map<int, int> count; // key是profix[i], value是profix[i]在遍历过程中相同值出现的次数. 比如数组是[1, 2, 3, -3], 那么profix[0] = 0, profix[1] = 1, profix[2] = 3, profix[3] = 6, profix[4] = 3. 那么count就是{0:1, 1:1, 3:2, 6:1}

        // 用哈希表count来记录在遍历过程中, 每个前缀和出现了多少次(如果整个数组是正的, 越加越大, 那麽每个前缀和只会出现一次.)
        count[0] = 1;   // profix[0]=0表示一个元素都没的空数组和. 它先出现了一次.
        
        int ans = 0; 

        // 遍历数组
        int cur = 0; // cur即profix[i]
        for(int n: nums){
            cur += n;
            // 查找有多少个前缀和 = cur - k
            if (count.find(cur - k) != count.end()){
                ans += count[cur - k]; // 如果存在这样的前缀和, 那么就把它的出现次数加到答案里
            }
            count[cur]++; // 将当前 `前缀和` 的值 加入哈希表计数.
        }
        return ans;
    }
};








