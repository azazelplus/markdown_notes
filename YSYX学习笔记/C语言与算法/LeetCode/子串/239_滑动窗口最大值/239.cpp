/*



给你一个整数数组 nums，有一个大小为 k 的滑动窗口从数组的最左侧移动到数组的最右侧。你只可以看到在滑动窗口内的 k 个数字。滑动窗口每次只向右移动一位。

返回 滑动窗口中的最大值 。


示例 1：

输入：nums = [1,3,-1,-3,5,3,6,7], k = 3
输出：[3,3,5,5,6,7]
解释：
滑动窗口的位置                最大值
---------------               -----
[1  3  -1] -3  5  3  6  7       3
 1 [3  -1  -3] 5  3  6  7       3
 1  3 [-1  -3  5] 3  6  7       5
 1  3  -1 [-3  5  3] 6  7       5
 1  3  -1  -3 [5  3  6] 7       6
 1  3  -1  -3  5 [3  6  7]      7
示例 2：

输入：nums = [1], k = 1
输出：[1]




显然可以暴力, 对每个窗口, 遍历窗口内的k个数, 找到最大值. 时间复杂度O(nk).

(这道题虽然叫做滑动窗口, 但是用滑动窗口的话)

更好的方法是单调队列: 维护一个双端的单调递减队列. 具体地: 
维护一个双端队列dq, 它存储nums元素的下标, 保证对应的值单调递减.
遍历数组nums, 

手动模拟示例:
nums = [1,3,-1,-3,5,3,6,7], k=3

| i | nums[i] | 操作（移除队首、弹出队尾、入队）         | 队中下标（对应值）        | 窗口范围 | 最大值 |
|---|---------|----------------------------------------|---------------------------|----------|--------|
| 0 | 1       | 入队0                                  | [0(1)]                    | -        | -      |
| 1 | 3       | 弹出队尾0（1≤3），入队1                | [1(3)]                    | -        | -      |
| 2 | -1      | 保留，入队2                            | [1(3),2(-1)]              | [0..2]   | 3      |
| 3 | -3      | 保留，入队3                            | [1(3),2(-1),3(-3)]        | [1..3]   | 3      |
| 4 | 5       | 弹出队尾3(-3),2(-1),1(3)（都≤5），入队4 | [4(5)]                    | [2..4]   | 5      |
| 5 | 3       | 保留（5>3），入队5                     | [4(5),5(3)]               | [3..5]   | 5      |
| 6 | 6       | 弹出队尾5(3),4(5)（都≤6），入队6       | [6(6)]                    | [4..6]   | 6      |
| 7 | 7       | 弹出队尾6(6)，入队7                    | [7(7)]                    | [5..7]   | 7      |


deque是双端队列. 有方法: 
    push_back(x)    在队尾插入元素x 
    pop_back()      删除队尾元素
    push_front(x)   在队首插入元素x
    pop_front()     删除队首元素
    back()          返回队尾元素
    front()         回队首元素 
    empty()         判断队列是否为空
*/

    
class Solution {
public:
    vector<int> maxSlidingWindow(vector<int>& nums, int k) {
        vector<int> ans;
        deque<int> dq; // 
        for(int i=0; i<nums.size(); i++){

            // 1. 移除已经离开窗口的队首下标
            if(!dq.empty() && dq.front() == i-k)    dq.pop_front();

            // 2. 移除队尾所有<=当前值nums[i]的下标, 因为它们不可能成为窗口内的最大值了
            while(!dq.empty() && nums[dq.back()] <= nums[i])    dq.pop_back();

            // 3. 将nums[i]的下标加入队尾. 此时nums[i]一定是队列里最小的. 这保证队列单调递减.
            dq.push_back(i);

            // 4. 如果窗口已经形成, 就将当前窗口的最大值加入答案
            if(i >= k-1)   ans.push_back(nums[dq.front()]);
        }
        return ans;
    }
};

